function h = colorswatch(rgb)
%COLORSWATCH Display a small swatch for an RGB color.
%
%   colorswatch([R G B])
%   h = colorswatch([R G B])
%
%   RGB values must be between 0 and 1.

    validateattributes(rgb, {'numeric'}, ...
        {'real', 'finite', 'vector', 'numel', 3, '>=', 0, '<=', 1});

    rgb = reshape(rgb, 1, 3);

    h = figure( ...
        'Color',       rgb, ...
        'MenuBar',     'none', ...
        'ToolBar',     'none', ...
        'NumberTitle', 'off', ...
        'Name',        sprintf('RGB: [%.3f %.3f %.3f]', rgb), ...
        'Position',    [500 500 200 200], ...
        'Resize',      'off', ...
        'WindowButtonDownFcn', @(src, ~) close(src));
    
end
